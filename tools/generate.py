class Model:
    def __init__(self, name, description=None, base=None):
        self.name = name
        self.description = description
        self.base = base
        self.props = []  # (wire, csname, cstype, is_date, description, required)


MODELS: dict[str, Model] = {}
ENUMS: dict[str, list] = {}
PENDING: list = []


def collect_props(schema):
    """Propriedades e obrigatórios de um schema (achatando allOf)."""
    schema = resolve(schema)
    props, required = {}, set()
    for part in schema.get("allOf") or []:
        p, r = collect_props(part)
        props.update(p)
        required |= r
    props.update(schema.get("properties") or {})
    required |= set(schema.get("required") or [])
    return props, required


def ensure_model(name, schema, description=None):
    """Registra a classe `name` para `schema` (objeto com propriedades)."""
    if name in MODELS:
        return name
    base = None
    own_schema = schema
    all_of = schema.get("allOf") or []
    refs = [p for p in all_of if "$ref" in p]
    inline = [p for p in all_of if "$ref" not in p]
    if len(refs) == 1 and len(all_of) >= 1 and not schema.get("properties"):
        base_name = ref_name(refs[0]["$ref"])
        base_schema = resolve(refs[0])
        if not is_enum_schema(base_schema) and (base_schema.get("properties") or base_schema.get("allOf")):
            base = ensure_model(base_name, base_schema)
            own_schema = {"allOf": inline}
    model = Model(name, description or schema.get("description"), base)
    MODELS[name] = model
    PENDING.append((model, own_schema))
    return name


def build_pending():
    while PENDING:
        model, schema = PENDING.pop(0)
        props, required = collect_props(schema)
        used = set(BASE_MEMBERS) | {model.name}
        base_wires = set()
        base = model.base
        while base:
            used |= {p[1] for p in MODELS[base].props}
            base_wires |= {p[0] for p in MODELS[base].props}
            base = MODELS[base].base
        for wire, ps in props.items():
            if wire in base_wires:
                continue  # já declarada na classe base (allOf)
            cs = pascal(wire)
            if cs in used:
                cs = cs + "Value"
            used.add(cs)
            cstype, is_date = cs_type(ps, model.name + pascal(wire))
            desc = resolve(ps).get("description") if isinstance(ps, dict) else None
            if isinstance(ps, dict) and "description" in ps:
                desc = ps["description"]
            model.props.append((wire, cs, cstype, is_date, desc, wire in required))


def nullable(t: str) -> str:
    return t if t.endswith("?") else t + "?"


def cs_type(schema, context: str, in_collection=False):
    """(tipo C#, é data) — sempre anulável fora de coleções."""
    if schema is None or schema == {} or schema is True:
        return ("JsonElement" if in_collection else "JsonElement?"), False
    if "$ref" in schema:
        name = ref_name(schema["$ref"])
        target = resolve(schema)
        if is_enum_schema(target):
            ENUMS.setdefault(name, target)
            return ("string" if in_collection else "string?"), False
        if target.get("properties") or target.get("allOf"):
            ensure_model(name, target)
            return (name if in_collection else name + "?"), False
        return cs_type(target, context, in_collection)
    if "allOf" in schema:
        parts = schema["allOf"]
        if len(parts) == 1:
            return cs_type(parts[0], context, in_collection)
        ensure_model(context, schema)
        return (context if in_collection else context + "?"), False
    for key in ("oneOf", "anyOf"):
        if key in schema:
            variants = [v for v in schema[key] if not (isinstance(v, dict) and v.get("type") == "null")]
            if len(variants) == 1:
                return cs_type(variants[0], context, in_collection)
            return ("JsonElement" if in_collection else "JsonElement?"), False
    t = base_type(schema)
    fmt = schema.get("format")
    if t == "string":
        if fmt == "date-time" and not in_collection:
            return "DateTimeOffset?", True
        return ("string" if in_collection else "string?"), False
    if t == "integer":
        v = "long" if fmt == "int64" else "int"
        return (v if in_collection else v + "?"), False
    if t == "number":
        return ("double" if in_collection else "double?"), False
    if t == "boolean":
        return ("bool" if in_collection else "bool?"), False
    if t == "array":
        item, _ = cs_type(schema.get("items") or {}, context + "Item", in_collection=True)
        v = f"List<{item}>"
        return (v if in_collection else v + "?"), False
    if t == "object" or "properties" in schema:
        if schema.get("properties"):
            ensure_model(context, schema)
            return (context if in_collection else context + "?"), False
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            val, _ = cs_type(ap, context + "Value", in_collection=True)
            v = f"Dictionary<string, {val}>"
            return (v if in_collection else v + "?"), False
        return ("JsonElement" if in_collection else "JsonElement?"), False
    return ("JsonElement" if in_collection else "JsonElement?"), False


