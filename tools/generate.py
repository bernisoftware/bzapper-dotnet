class Op:
    pass


def load_ops():
    cases = json.loads(CASES.read_text(encoding="utf-8"))
    wanted = set(cases["ops"])
    ops = []
    for path, item in SPEC_DOC["paths"].items():
        for method in METHODS:
            raw = item.get(method)
            if not raw or raw.get("operationId") not in wanted:
                continue
            op = Op()
            op.id = raw["operationId"]
            op.method = method.upper()
            op.path = path
            op.summary = raw.get("summary")
            op.description = raw.get("description")
            op.tag = (raw.get("tags") or ["misc"])[0]
            op.partner = path.startswith("/partner/")
            op.path_params, op.query_params = [], []
            for p in (item.get("parameters") or []) + (raw.get("parameters") or []):
                p = resolve(p)
                if p["in"] == "path":
                    op.path_params.append(p)
                elif p["in"] == "query":
                    op.query_params.append(p)
            op.body_kind, op.body_type = None, None
            rb = resolve(raw.get("requestBody")) if raw.get("requestBody") else None
            if rb:
                ct, media = next(iter(rb["content"].items()))
                schema = media.get("schema") or {}
                if ct.startswith("multipart/"):
                    op.body_kind = "multipart"
                    op.multipart_fields = [k for k in (resolve(schema).get("properties") or {}) if k != "file"]
                else:
                    op.body_kind = "json"
                    pinned_body = published_body_type(op)
                    if "$ref" in schema and pinned_body and pinned_body != ref_name(schema["$ref"]) \
                            and not is_enum_schema(resolve(schema)):
                        # A spec deu nome (ou outro nome) ao schema do corpo depois de publicado: o modelo
                        # segue saindo com o nome PUBLICADO (renomear a classe quebraria quem a instancia).
                        ensure_model(pinned_body, resolve(schema), resolve(schema).get("description"))
                        op.body_type = pinned_body
                    elif "$ref" in schema:
                        op.body_type, _ = cs_type(schema, pascal(op.id) + "Request")
                        op.body_type = op.body_type.rstrip("?")
                    else:
                        name = pascal(op.id) + "Request"
                        ensure_model(name, schema, schema.get("description"))
                        op.body_type = name
            op.ret = "void"
            op.ret_nullable = False
            op.undocumented = False
            for code, resp in (raw.get("responses") or {}).items():
                if not str(code).startswith("2"):
                    continue
                resp = resolve(resp)
                content = resp.get("content")
                if int(str(code)) == 204:
                    op.ret = "void"
                    continue
                if not content:
                    # 2xx sem schema na spec: devolve o JSON que vier (null sem corpo) em vez de descartá-lo.
                    op.ret = "json"
                    op.undocumented = True
                    break
                media = content.get("application/json") or next(iter(content.values()))
                schema = media.get("schema")
                if not schema:
                    op.ret = "json"
                    break
                nullable_ret = any(isinstance(v, dict) and v.get("type") == "null" for v in (schema.get("oneOf") or []))
                t, _ = cs_type(schema, pascal(op.id) + "Result")
                if t.startswith("JsonElement"):
                    op.ret = "json"
                else:
                    op.ret = t.rstrip("?")
                    op.ret_nullable = nullable_ret
                break
            ops.append(op)
    for op in ops:
        apply_baseline(op)
    missing = wanted - {o.id for o in ops}
    if missing:
        raise SystemExit(f"ops de cases.json sem operação na spec: {sorted(missing)}")
    return ops


def published_body_type(op):
    """Tipo do parâmetro `request` na superfície publicada (None se a op é nova ou não tinha corpo JSON)."""
    base = BASELINE.get(op.id)
    for p in (base or {}).get("params") or []:
        t, n = p.rsplit(" ", 1)
        if n == "request":
            return t
    return None


def apply_baseline(op):
    """Trava a op na superfície publicada (tools/api-baseline.json); aborta se a quebraria."""
    op.typed_ret = None  # retorno tipado aditivo (XxxTypedAsync) quando o XxxAsync publicado é JsonElement?
    op.pinned_names = None
    base = BASELINE.get(op.id)
    if not base:
        return  # op nova: superfície livre
    errors = []
    cls = "PartnerClient" if op.partner else "BzapperClient"
    if base["class"] != cls:
        errors.append(f"mudou de classe ({base['class']} → {cls})")
    new_ret = return_type(op)
    if new_ret != base["returns"]:
        if base["returns"] == JSON_RET and op.ret not in ("void", "json"):
            op.typed_ret = (op.ret, op.ret_nullable)
            op.ret, op.ret_nullable = "json", False
        else:
            errors.append(f"retorno {base['returns']} → {new_ret}")
    old = [x.rsplit(" ", 1) for x in base["params"]]
    new = signature(op)
    if len(old) != len(new):
        errors.append(f"parâmetros {base['params']} → {[f'{t} {n}' for n, t, *_ in new]}")
    else:
        for (ot, on), (n, t, *_rest) in zip(old, new):
            if ot != t:
                errors.append(f"parâmetro {on}: tipo {ot} → {t}")
        op.pinned_names = [on for _t, on in old]
    if errors:
        raise SystemExit(f"{op.id}: quebraria a superfície publicada {BASELINE_FILE.name}: " + "; ".join(errors))


def query_cs(p):
    s = resolve(p.get("schema") or {"type": "string"})
    t = base_type(s)
    if t == "integer":
        return "long" if s.get("format") == "int64" else "int"
    if t == "boolean":
        return "bool"
    if t == "number":
        return "double"
    if t == "array":
        return "IEnumerable<string>"
    if t == "string" and s.get("format") == "date-time":
        return "DateTimeOffset"
    return "string"


def signature(op):
    """Lista de (csname, cstype, default, kind, wire) na ordem da assinatura."""
    params = []
    used = set(RESERVED_PARAMS)
    for p in op.path_params:
        n = camel(p["name"])
        used.add(n)
        params.append((n, "string", None, "path", p["name"], p))
    if op.body_kind == "json":
        params.append(("request", op.body_type, None, "body", None, None))
    elif op.body_kind == "multipart":
        params.append(("file", "FileUpload", None, "file", None, None))
    req_q = [p for p in op.query_params if p.get("required")]
    opt_q = [p for p in op.query_params if not p.get("required")]
    for p in req_q + opt_q:
        n = camel(p["name"])
        if n in used:
            n = n + "Param"
        used.add(n)
        t = query_cs(p)
        if p.get("required"):
            params.append((n, t, None, "query", p["name"], p))
        else:
            params.append((n, t + "?", "null", "query", p["name"], p))
    if getattr(op, "pinned_names", None):
        params = [(pin,) + tuple(x[1:]) for pin, x in zip(op.pinned_names, params)]
    return params


def return_type(op, typed=False):
    if typed:
        t, nullable_ret = op.typed_ret
        return f"Task<{t}?>" if nullable_ret else f"Task<{t}>"
    if op.ret == "void":
        return "Task"
    if op.ret == "json":
        return "Task<JsonElement?>"
    return f"Task<{op.ret}?>" if op.ret_nullable else f"Task<{op.ret}>"


def emit_method(op, http_field, typed=False):
    params = signature(op)
    ret, ret_nullable = op.typed_ret if typed else (op.ret, op.ret_nullable)
    name = pascal_op(op.id) + ("TypedAsync" if typed else "Async")
    lines = []
    summary = xml(op.summary or op.id)
    lines.append(f"    /// <summary>{summary} — <c>{op.method} {xml(op.path)}</c>.</summary>")
    if op.description:
        lines.append(f"    /// <remarks>{xml(op.description)}</remarks>")
    if typed:
        lines.append(f"    /// <remarks>Versão tipada de <see cref=\"{pascal_op(op.id)}Async\"/> (que segue devolvendo <c>JsonElement?</c> por compatibilidade).</remarks>")
    elif op.typed_ret:
        lines.append(f"    /// <remarks>Devolve o JSON cru por compatibilidade com versões anteriores; prefira <see cref=\"{pascal_op(op.id)}TypedAsync\"/>, que devolve <see cref=\"{op.typed_ret[0]}\"/>.</remarks>")
    for n, t, d, kind, wire, p in params:
        n_doc = n.lstrip("@")
        if kind == "body":
            lines.append(f"    /// <param name=\"{n_doc}\">Corpo da requisição (<see cref=\"{t}\"/>).</param>")
        elif kind == "file":
            lines.append(f"    /// <param name=\"{n_doc}\">Arquivo enviado como <c>multipart/form-data</c> (campo <c>file</c>).</param>")
        else:
            desc = xml((p or {}).get("description") or "")
            where = "caminho" if kind == "path" else "query"
            req = "" if d is not None else " Obrigatório."
            lines.append(f"    /// <param name=\"{n_doc}\"><c>{wire}</c> ({where}).{req} {desc}</param>".replace(" </param>", "</param>"))
    lines.append("    /// <param name=\"options\">Opções desta chamada (Idempotency-Key própria, tempo limite, projeto).</param>")
    lines.append("    /// <param name=\"cancellationToken\">Cancelamento.</param>")
    if ret == "void":
        lines.append("    /// <returns>Nada (a API responde sem corpo).</returns>")
    elif ret == "json":
        lines.append("    /// <returns>O JSON devolvido pela API (<c>null</c> quando a resposta vem sem corpo).</returns>")
    else:
        lines.append(f"    /// <returns>O objeto <see cref=\"{ret}\"/> devolvido pela API.</returns>")
    lines.append("    /// <exception cref=\"BzapperException\">Erro da API ou de rede (use <see cref=\"BzapperException.Code\"/>).</exception>")
    lines.append("    /// <exception cref=\"ArgumentException\">Parâmetro de caminho vazio, <c>.</c> ou <c>..</c> (antes de qualquer requisição).</exception>")
    sig = ", ".join(f"{t} {n}" + (f" = {d}" if d is not None else "") for n, t, d, kind, wire, p in params)
    sig = (sig + ", " if sig else "") + "RequestOptions? options = null, CancellationToken cancellationToken = default"
    lines.append(f"    public {return_type(op, typed)} {name}({sig})")
    lines.append("    {")
    # caminho
    path_expr = '"' + op.path + '"'
    for n, t, d, kind, wire, p in params:
        if kind == "path":
            path_expr = path_expr.replace("{" + wire + "}", f'" + PathSegment.Encode({n}, "{wire}") + "')
    path_expr = path_expr.replace(' + ""', "")
    lines.append(f"        var path = {path_expr};")
    for n, t, d, kind, wire, p in params:
        if kind in ("body", "file"):
            lines.append(f"        if ({n} is null) throw new ArgumentNullException(nameof({n}));")
        if kind == "query" and d is None and not t.endswith("?") and t in ("string", "IEnumerable<string>"):
            lines.append(f"        if ({n} is null) throw new ArgumentNullException(nameof({n}));")
    q = [x for x in params if x[3] == "query"]
    if q:
        chain = "".join(f'.Add("{wire}", {n})' for n, t, d, kind, wire, p in q)
        lines.append(f"        var query = new Query(){chain};")
        qarg = "query"
    else:
        qarg = "null"
    if op.body_kind == "json":
        barg = "RequestBody.Json(request)"
    elif op.body_kind == "multipart":
        barg = "RequestBody.Multipart(file)"
    else:
        barg = "null"
    method = {"GET": "HttpMethod.Get", "POST": "HttpMethod.Post", "PUT": "HttpMethod.Put", "DELETE": "HttpMethod.Delete", "PATCH": "BzapperHttp.Patch"}[op.method]
    call_args = f"{method}, path, {qarg}, {barg}, options, cancellationToken"
    if ret == "void":
        lines.append(f"        return {http_field}.SendVoidAsync({call_args});")
    elif ret == "json":
        lines.append(f"        return {http_field}.SendJsonAsync({call_args});")
    elif ret_nullable:
        lines.append(f"        return {http_field}.SendNullableAsync<{ret}>({call_args});")
    else:
        lines.append(f"        return {http_field}.SendAsync<{ret}>({call_args});")
    lines.append("    }")
    return "\n".join(lines)


def pascal_op(op_id: str) -> str:
    return op_id[:1].upper() + op_id[1:]


def emit_client(ops, cls, http_field, doc):
    out = [HEADER, "#nullable enable", "using System;", "using System.Collections.Generic;", "using System.Net.Http;",
           "using System.Text.Json;", "using System.Threading;", "using System.Threading.Tasks;", "using Bzapper.Internal;", "",
           "namespace Bzapper;", "", f"/// <summary>{doc}</summary>", f"public sealed partial class {cls}", "{"]
    tag = None
    for op in sorted(ops, key=lambda o: (o.tag, o.id)):
        if op.tag != tag:
            tag = op.tag
            out.append(f"    // ── {tag} " + "─" * max(4, 100 - len(tag)))
            out.append("")
        out.append(emit_method(op, http_field))
        out.append("")
        if op.typed_ret:
            out.append(emit_method(op, http_field, typed=True))
            out.append("")
    out[-1] = "}"
    return "\n".join(out) + "\n"


def emit_models():
    out = [HEADER, "#nullable enable", "#pragma warning disable CS1591 // campos sem descrição na spec", "using System;",
           "using System.Collections.Generic;", "using System.Text.Json;", "using System.Text.Json.Serialization;",
           "using Bzapper.Internal;", "", "namespace Bzapper;", ""]
    for name in sorted(MODELS):
        m = MODELS[name]
        if m.description:
            out.append(f"/// <summary>{xml(m.description)}</summary>")
        else:
            out.append(f"/// <summary><c>{name}</c> (veja a referência da API).</summary>")
        base = m.base or "BzapperObject"
        out.append(f"public class {name} : {base}")
        out.append("{")
        for wire, cs, t, is_date, desc, required in m.props:
            d = xml(desc or "")
            if required:
                d = (d + " Obrigatório.").strip()
            out.append(f"    /// <summary><c>{wire}</c>{' — ' + d if d else ''}</summary>")
            out.append(f"    [JsonPropertyName(\"{wire}\")]")
            out.append("    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]")
            if is_date:
                out.append("    [JsonConverter(typeof(UtcDateTimeConverter))]")
            out.append(f"    public {t} {cs} {{ get; set; }}")
            out.append("")
        if out[-1] == "":
            out.pop()
        out.append("}")
        out.append("")
    for name in sorted(ENUMS):
        s = ENUMS[name]
        out.append(f"/// <summary>Valores conhecidos de <c>{name}</c>{' — ' + xml(s.get('description')) if s.get('description') else ''}. A API pode ganhar valores novos: trate o campo como <c>string</c>.</summary>")
        out.append(f"public static class {name}Values")
        out.append("{")
        seen = set()
        for v in s["enum"]:
            if v is None:
                continue
            ident = pascal(str(v)) if str(v) else "Empty"
            while ident in seen:
                ident += "_"
            seen.add(ident)
            out.append(f"    /// <summary><c>{xml(v)}</c></summary>")
            out.append(f"    public const string {ident} = \"{v}\";")
            out.append("")
        if out[-1] == "":
            out.pop()
        out.append("}")
        out.append("")
    return "\n".join(out)


