#!/usr/bin/env python3
"""Gera a superfície tipada da SDK .NET do bZapper a partir de packages/sdk/openapi.yaml.

Saídas (não edite à mão — rode de novo este script):
  src/Bzapper/Generated/Models.g.cs                   modelos (corpos e respostas) + constantes de enum
  src/Bzapper/Generated/BzapperClient.Operations.g.cs um método XxxAsync por operação (BRIEF §6)
  src/Bzapper/Generated/PartnerClient.Operations.g.cs as operações do bZapper Connect (/partner/*)
  tests/Bzapper.Tests/OpTable.g.cs                    tabela op → chamada da conformidade (BRIEF §7)

As operações vêm de tests/Bzapper.Tests/fixtures/cases.json ("ops"): o que está lá precisa virar método.

Compatibilidade (tools/api-baseline.json = superfície PUBLICADA no NuGet): todo XxxAsync que já existia mantém
retorno, tipos e NOMES de parâmetros (argumento nomeado é contrato de fonte em C#). Se a spec renomear um
parâmetro de caminho, o nome publicado vence. Se uma op que devolvia JsonElement? ganhar schema, XxxAsync
continua devolvendo JsonElement? e o tipo novo sai, aditivo, em XxxTypedAsync. Qualquer outra divergência
(tipo/parâmetro/retorno) aborta a geração: só se quebra a superfície numa versão major (aí regrave o baseline).
Só roda no monorepo (a spec não vai para o espelho público):

  python3 clients/dotnet/tools/generate.py
"""
