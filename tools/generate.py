def emit_table(ops):
    out = [HEADER, "#nullable enable", "using System.Text.Json;", "using Bzapper.Tests.Support;", "", "namespace Bzapper.Tests;", "",
           "/// <summary>",
           "/// op de <c>cases.json</c> → chamada idiomática da SDK. Caso com op fora desta tabela (e fora de",
           "/// <c>sdk_excluded_ops</c>) FALHA: é assim que endpoint novo sem método na SDK quebra o build.",
           "/// </summary>",
           "internal static partial class OpTable",
           "{",
           "    public delegate Task<object?> Call(BzapperClient client, PartnerClient partner, Args args, RequestOptions? options);",
           "",
           "    public static readonly IReadOnlyDictionary<string, Call> Ops = new Dictionary<string, Call>",
           "    {"]
    for op in sorted(ops, key=lambda o: o.id):
        target = "p" if op.partner else "c"
        args = []
        for n, t, d, kind, wire, p in signature(op):
            if kind == "path":
                expr = f'a.Path("{wire}")'
            elif kind == "body":
                expr = f"a.Body<{t}>()"
            elif kind == "file":
                expr = "a.File()"
            else:
                base = t.rstrip("?")
                fn = {"string": "QStr", "int": "QInt", "long": "QLong", "bool": "QBool", "double": "QDouble",
                      "DateTimeOffset": "QDate", "IEnumerable<string>": "QList"}[base]
                expr = f'a.{fn}("{wire}")'
                if d is None:
                    expr += "!" if base in ("string", "IEnumerable<string>") else ".Value"
                else:
                    expr = f"{n.lstrip('@')}: {expr}"
            args.append(expr)
        if op.body_kind is None:
            args_pre = ["a.NoBody()"]
        else:
            args_pre = []
        call_args = ", ".join(args + ["options: o"])
        pre = "".join(f"{x}; " for x in args_pre)
        # op com XxxTypedAsync (compat): a conformidade exercita a versão tipada.
        method = pascal_op(op.id) + ("TypedAsync" if op.typed_ret else "Async")
        if op.ret == "void":
            body = f"{{ {pre}await {target}.{method}({call_args}); return null; }}"
        else:
            body = f"{{ {pre}return await {target}.{method}({call_args}); }}"
        out.append(f"        [\"{op.id}\"] = async (c, p, a, o) => {body},")
    out.append("    };")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    ops = load_ops()
    build_pending()
    client_ops = [o for o in ops if not o.partner]
    partner_ops = [o for o in ops if o.partner]
    files = {
        OUT_MODELS: emit_models(),
        OUT_CLIENT: emit_client(client_ops, "BzapperClient", "Http",
                                "Operações da API do bZapper (uma por <c>operationId</c> da spec, em <c>XxxAsync</c>)."),
        OUT_PARTNER: emit_client(partner_ops, "PartnerClient", "Http",
                                 "Operações do bZapper Connect (parceiro)."),
        OUT_TABLE: emit_table(ops),
    }
    check = "--check" in sys.argv
    stale = []
    for path, text in files.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(DOTNET)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    if stale:
        raise SystemExit("desatualizado (rode clients/dotnet/tools/generate.py): " + ", ".join(stale))
    compat = sorted(o.id for o in ops if o.typed_ret)
    if compat:
        print(f"{len(compat)} ops com XxxTypedAsync (XxxAsync segue JsonElement? por compatibilidade): {', '.join(compat)}")
    undocumented = sorted(o.id for o in ops if o.undocumented)
    if undocumented:
        print(f"{len(undocumented)} ops com 2xx sem schema na spec (retornam JsonElement?): {', '.join(undocumented)}")
    print(f"{len(ops)} operações ({len(partner_ops)} do Connect), {len(MODELS)} modelos, {len(ENUMS)} enums")


if __name__ == "__main__":
    main()
